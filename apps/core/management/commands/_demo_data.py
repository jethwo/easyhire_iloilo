def credentials_text():
    """The text of the credentials file, in the requested format."""
    out = ["# EMPLOYERS (10 companies)", ""]
    for co in COMPANIES:
        out += [f"email: {employer_email(co)}", f"password: {PASSWORD}", ""]
    out += ["# JOBSEEKERS (15 users)", ""]
    for js in JOBSEEKERS:
        out += [f"email: {jobseeker_email(js)}", f"password: {PASSWORD}", ""]
